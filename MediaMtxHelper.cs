using System.Diagnostics;

namespace HS175D
{
    /// <summary>
    /// Manages a bundled <c>mediamtx.exe</c> that pulls the drone's RTSP H.264 stream and re-serves it as
    /// browser-playable WebRTC (WHEP) on port 8889. MediaMTX binds 0.0.0.0 itself, so the Quest/phone reach
    /// the video directly — no Windows URL-ACL needed (unlike the StudioWeb control server).
    ///
    /// The exe is optional: if it isn't found next to the app, video is simply unavailable and the rest of
    /// Studio Web (HUD + control) still works. Download mediamtx.exe from github.com/bluenviron/mediamtx and
    /// drop it in the app folder (or a <c>mediamtx\</c> subfolder).
    /// </summary>
    public static class MediaMtxHelper
    {
        public const int WebRtcPort = 8889;
        public const string PathName = "cam";        // MediaMTX path → WHEP at http://&lt;ip&gt;:8889/cam/whep

        static Process? _proc;
        static Action<string>? _log;

        public static bool Running => _proc is { HasExited: false };
        public static string? ExePath { get; private set; }

        static string? FindExe()
        {
            string baseDir = AppContext.BaseDirectory;
            foreach (var rel in new[] { "mediamtx.exe", @"mediamtx\mediamtx.exe" })
            {
                string p = Path.Combine(baseDir, rel);
                if (File.Exists(p)) return p;
            }
            return null;
        }

        /// <summary>Start MediaMTX against the drone's RTSP H.264 stream. Returns false if the exe is missing.</summary>
        public static bool Start(string droneIp, Action<string>? log)
        {
            _log = log;
            if (Running) return true;

            ExePath = FindExe();
            if (ExePath == null)
            {
                _log?.Invoke("MediaMTX not found — drop mediamtx.exe next to the app for browser video. " +
                             "HUD + control still work without it.");
                return false;
            }

            // H.264 path only — H.265 is not WebRTC-playable in browsers.
            string rtsp = $"rtsp://hy_syma:ls155633@{droneIp}:19200/HYSymaH264VideoSMS";
            string cfgPath = Path.Combine(AppContext.BaseDirectory, "mediamtx_studio.yml");
            try { File.WriteAllText(cfgPath, BuildConfig(rtsp)); }
            catch (Exception ex) { _log?.Invoke("MediaMTX config write failed: " + ex.Message); return false; }

            try
            {
                var psi = new ProcessStartInfo(ExePath, $"\"{cfgPath}\"")
                {
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    WorkingDirectory = AppContext.BaseDirectory
                };
                _proc = Process.Start(psi);
                if (_proc == null) { _log?.Invoke("MediaMTX failed to start."); return false; }
                _proc.OutputDataReceived += (s, e) => { if (e.Data != null) _log?.Invoke("[mediamtx] " + e.Data); };
                _proc.ErrorDataReceived  += (s, e) => { if (e.Data != null) _log?.Invoke("[mediamtx] " + e.Data); };
                _proc.BeginOutputReadLine();
                _proc.BeginErrorReadLine();
                _log?.Invoke($"MediaMTX started → WebRTC on :{WebRtcPort}/{PathName} (pulling {rtsp})");
                return true;
            }
            catch (Exception ex) { _log?.Invoke("MediaMTX start error: " + ex.Message); return false; }
        }

        public static void Stop()
        {
            try { if (_proc is { HasExited: false }) { _proc.Kill(entireProcessTree: true); _proc.WaitForExit(2000); } }
            catch { }
            finally { try { _proc?.Dispose(); } catch { } _proc = null; }
        }

        // Minimal config: only the WebRTC server + one on-demand path; other servers off to avoid port clashes.
        static string BuildConfig(string rtsp) =>
$@"# auto-generated by Drone RE Studio — do not edit (regenerated on each start)
logLevel: info
api: no
rtsp: no
rtmp: no
hls: no
srt: no
webrtc: yes
webrtcAddress: :{WebRtcPort}
webrtcLocalUDPAddress: :8189
paths:
  {PathName}:
    source: {rtsp}
    sourceOnDemand: yes
    sourceProtocol: tcp
";
    }
}
